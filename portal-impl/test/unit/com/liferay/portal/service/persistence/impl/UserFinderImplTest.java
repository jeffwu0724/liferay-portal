package com.liferay.portal.service.persistence.impl;

import com.liferay.portal.kernel.util.comparator.UserIdComparator;
import com.liferay.portal.test.rule.LiferayUnitTestRule;

import org.junit.Assert;
import org.junit.ClassRule;
import org.junit.Rule;
import org.junit.Test;

/**
 * @author Jiefeng Wu
 */
public class UserFinderImplTest {

	@ClassRule
	@Rule
	public static final LiferayUnitTestRule liferayUnitTestRule =
		LiferayUnitTestRule.INSTANCE;

	@Test
	public void testGetColumnNamesOrderByUserId() {
		UserFinderImpl userFinderImpl = new UserFinderImpl();

		Assert.assertEquals(
			"DISTINCT User_.userId AS userId",
			userFinderImpl.getColumnNames(UserIdComparator.getInstance(true)));
	}

}